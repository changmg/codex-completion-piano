'use strict';

const vscode = require('vscode');
const { execFile } = require('node:child_process');
const { createHash } = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');

const EVENT_FILE = null; // Set by the Linux installer or build.py --marker-path.

function activate(context) {
  const log = vscode.window.createOutputChannel('Codex Completion Piano');
  const seen = new Map();
  const readErrors = new Map();
  let polling = false;
  let playing = false;
  let disposed = false;
  let player;
  let lastPlayback;
  let lastRead;
  let lastCleanup = 0;

  function signalUri(authority) {
    const paths = vscode.workspace.getConfiguration('codexCompletionPiano').get('markerPaths', {});
    const eventFile = Object.prototype.hasOwnProperty.call(paths, authority) ? paths[authority] : EVENT_FILE;
    if (typeof eventFile !== 'string' || !eventFile.startsWith('/')) {
      throw new Error('Configure an absolute remote path in Codex Completion Piano: Marker Paths, or install the VSIX generated by the Linux installer.');
    }
    return vscode.Uri.from({ scheme: 'vscode-remote', authority, path: eventFile });
  }

  async function claimEvent(uri, eventId) {
    // UI extension storage is shared by all VS Code windows in this profile.
    // Exclusive file creation lets only one window play each host's event.
    const directory = path.join(context.globalStorageUri.fsPath, 'played-completions');
    await fs.mkdir(directory, { recursive: true });
    const now = Date.now();
    if (now - lastCleanup > 60000) {
      lastCleanup = now;
      for (const name of await fs.readdir(directory)) {
        if (!/^[a-f0-9]{64}$/.test(name)) continue;
        const file = path.join(directory, name);
        try {
          if (now - (await fs.stat(file)).mtimeMs > 86400000) await fs.unlink(file);
        } catch (error) {
          if (error.code !== 'ENOENT') log.appendLine(`Cannot clean playback receipt: ${error.message}`);
        }
      }
    }
    const name = createHash('sha256').update(uri.toString()).update('\0').update(eventId).digest('hex');
    try {
      await fs.writeFile(path.join(directory, name), '', { flag: 'wx' });
      return true;
    } catch (error) {
      if (error.code === 'EEXIST') return false;
      throw error;
    }
  }

  async function readSignal(uri, timeoutMs = 10000) {
    let timeout;
    try {
      return await Promise.race([
        vscode.workspace.fs.readFile(uri),
        new Promise((_, reject) => { timeout = setTimeout(() => reject(new Error('Remote completion read timed out; retrying.')), timeoutMs); })
      ]);
    } finally {
      clearTimeout(timeout);
    }
  }

  async function diagnose() {
    const folders = vscode.workspace.workspaceFolders || [];
    const report = {
      version: context.extension.packageJSON.version,
      platform: process.platform,
      remoteName: vscode.env.remoteName,
      enabled: vscode.workspace.getConfiguration('codexCompletionPiano').get('enabled', true),
      scope: vscode.workspace.getConfiguration('codexCompletionPiano').get('scope', 'machine'),
      polling,
      lastRead,
      lastPlayback,
      readErrors: Object.fromEntries(readErrors),
      folders: folders.map(folder => ({ uri: folder.uri.toString(), path: folder.uri.path })),
      signals: []
    };
    for (const authority of new Set(folders.filter(folder => folder.uri.scheme === 'vscode-remote').map(folder => folder.uri.authority))) {
      const signal = { authority };
      try {
        const uri = signalUri(authority);
        signal.uri = uri.toString();
        signal.previous = seen.get(signal.uri);
        const bytes = await readSignal(uri, 5000);
        signal.event = JSON.parse(Buffer.from(bytes).toString('utf8'));
        signal.matches = folders.some(folder => {
          const root = folder.uri.path.replace(/\/+$/, '') || '/';
          return folder.uri.authority === authority && typeof signal.event.cwd === 'string' &&
            (signal.event.cwd === root || signal.event.cwd.startsWith(root === '/' ? '/' : root + '/'));
        });
        signal.eligible = report.enabled && (report.scope === 'machine' || signal.matches);
      } catch (error) {
        signal.error = { code: error.code, message: error.message };
      }
      report.signals.push(signal);
    }
    log.appendLine(JSON.stringify(report, null, 2));
    return report;
  }

  function play(preview = false, eventId) {
    if (process.platform !== 'win32') {
      if (preview) {
        vscode.window.showErrorMessage('Install Codex Completion Piano locally in Windows VS Code to play this sound.');
      }
      return Promise.resolve(false);
    }
    if (playing || disposed) return Promise.resolve(false);
    playing = true;
    const playback = { source: preview ? 'preview' : 'completion', eventId, startedAt: new Date().toISOString(), status: 'playing' };
    lastPlayback = playback;
    const executable = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
    const command = [
      "$ErrorActionPreference = 'Stop'",
      '$sound = New-Object System.Media.SoundPlayer',
      '$sound.SoundLocation = $env:CODEX_COMPLETION_PIANO_WAV',
      '$sound.Load()',
      '$sound.PlaySync()',
      '$sound.Dispose()'
    ].join('; ');
    return new Promise(resolve => {
      player = execFile(executable, ['-NoProfile', '-NonInteractive', '-Command', command], {
        windowsHide: true,
        timeout: 10000,
        env: {
          ...process.env,
          CODEX_COMPLETION_PIANO_WAV: context.asAbsolutePath('piano.wav')
        }
      }, error => {
        playing = false;
        player = undefined;
        playback.finishedAt = new Date().toISOString();
        playback.status = error ? 'failed' : 'completed';
        if (error) playback.error = error.message;
        log.appendLine(`${playback.source} playback ${playback.status}${eventId ? ' for ' + eventId : ''}.`);
        if (error) {
          log.appendLine(`Playback failed: ${error.message}`);
          if (preview) vscode.window.showErrorMessage('Piano playback failed. See the Codex Completion Piano output channel.');
        }
        resolve(!error);
      });
    });
  }

  async function poll() {
    if (polling || disposed || process.platform !== 'win32') return;
    polling = true;
    try {
      const folders = (vscode.workspace.workspaceFolders || [])
        .filter(folder => folder.uri.scheme === 'vscode-remote');
      const authorities = new Set(folders.map(folder => folder.uri.authority));
      for (const authority of authorities) {
        let key = authority;
        try {
          const uri = signalUri(authority);
          key = uri.toString();
          const startedAt = Date.now();
          const bytes = await readSignal(uri);
          lastRead = { completedAt: new Date().toISOString(), durationMs: Date.now() - startedAt };
          readErrors.delete(key);
          if (disposed || bytes.length > 4096) continue;
          const event = JSON.parse(Buffer.from(bytes).toString('utf8'));
          if (!event || event.type !== 'agent-turn-complete' || typeof event.id !== 'string') continue;
          const initialized = seen.has(key);
          const previous = seen.get(key);
          seen.set(key, event.id);
          // Establish a baseline on startup so old completions do not play again.
          if (!initialized || previous === event.id) continue;
          const enabled = vscode.workspace.getConfiguration('codexCompletionPiano').get('enabled', true);
          if (!enabled || typeof event.cwd !== 'string') continue;
          const belongsHere = folders.some(folder => {
            const root = folder.uri.path.replace(/\/+$/, '') || '/';
            return folder.uri.authority === authority &&
              (event.cwd === root || event.cwd.startsWith(root === '/' ? '/' : root + '/'));
          });
          const scope = vscode.workspace.getConfiguration('codexCompletionPiano').get('scope', 'machine');
          if (scope === 'workspace' && !belongsHere) {
            log.appendLine(`Skipped completion ${event.id}: ${event.cwd} is outside this workspace.`);
            continue;
          }
          if (!playing && await claimEvent(uri, event.id)) await play(false, event.id);
        } catch (error) {
          if (readErrors.get(key) !== error.message) {
            log.appendLine(`Cannot process ${key}: ${error.message}`);
            readErrors.set(key, error.message);
          }
          // No marker yet is a valid baseline; tolerate disconnected SSH sessions.
          if (error && error.code === 'FileNotFound') seen.set(key, null);
        }
      }
    } finally {
      polling = false;
    }
  }

  context.subscriptions.push(log);
  context.subscriptions.push(vscode.commands.registerCommand('codexCompletionPiano.preview', () => play(true)));
  context.subscriptions.push(vscode.commands.registerCommand('codexCompletionPiano.diagnose', diagnose));
  const timer = setInterval(() => void poll(), 750);
  context.subscriptions.push({ dispose() {
    disposed = true;
    clearInterval(timer);
    if (player) player.kill();
  }});
  void poll();
  log.appendLine('Ready. Play a preview with “Codex: Preview Piano Notification”.');
}

module.exports = { activate };
